//! CI/CD template generation for zenv validation workflows

use crate::errors::CliError;

/// Available template names
pub const TEMPLATES: &[&str] = &["github", "gitlab", "circleci"];

/// Public GitHub release URL for the prebuilt zenv linux-x64 binary.
/// Hoisted here so the three template generators stay in sync if the
/// download URL ever changes.
const RELEASE_BINARY_URL: &str = concat!(
    env!("CARGO_PKG_REPOSITORY"),
    "/releases/download/v",
    env!("CARGO_PKG_VERSION"),
    "/zenv-linux"
);

/// Default Rust image for `cargo install`-style CI templates (CircleCI).
const RUST_CIRCLE_IMAGE: &str = concat!("cimg/rust:", env!("CARGO_PKG_RUST_VERSION"));

/// Match the glibc baseline of the Linux release build; Alpine uses musl.
const BINARY_IMAGE: &str = "ubuntu:24.04";

/// Default Rust image for source-install CI templates (GitLab).
const RUST_LATEST_IMAGE: &str = "rust:latest";

/// Generate CI/CD template for the given platform
#[doc(hidden)]
pub fn run(
    template: &str,
    output: Option<&str>,
    list: bool,
    use_binary: bool,
) -> Result<(), CliError> {
    if list {
        println!("Available templates:");
        for name in TEMPLATES {
            println!("  {}", name);
        }
        return Ok(());
    }

    let content = match template.to_lowercase().as_str() {
        "github" | "gh" | "github-actions" => github_actions_template(use_binary),
        "gitlab" | "gl" | "gitlab-ci" => gitlab_ci_template(use_binary),
        "circleci" | "circle" => circleci_template(use_binary),
        _ => {
            return Err(CliError::Input(format!(
                "Unknown template: '{}'. Available: {}",
                template,
                TEMPLATES.join(", ")
            )))
        }
    };

    match output {
        Some(path) => {
            crate::remote::write_atomic(std::path::Path::new(path), content.as_bytes())
                .map_err(|e| CliError::Input(format!("Failed to write {}: {}", path, e)))?;
            println!("Template written to {}", path);
        }
        None => {
            print!("{}", content);
        }
    }

    Ok(())
}

/// GitHub Actions workflow template
fn github_actions_template(use_binary: bool) -> String {
    let install_step = if use_binary {
        format!(
            r#"      - name: Install zenv
        run: |
          curl -fsSL {} -o zenv
          chmod +x zenv
          sudo mv zenv /usr/local/bin/"#,
            RELEASE_BINARY_URL
        )
    } else {
        r#"      - name: Install zenv
        run: cargo install zorath-env --locked"#
            .to_string()
    };

    format!(
        r#"# .github/workflows/env-validation.yml
# Generated by zenv template github{}
name: Validate Environment

on:
  push:
    paths:
      - '.env*'
      - 'env.schema.json'
      - 'env.schema.yaml'
  pull_request:
    paths:
      - '.env*'
      - 'env.schema.json'
      - 'env.schema.yaml'

jobs:
  validate:
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4

{}

      - name: Validate .env
        run: zenv check --allow-missing-env

      # Optional: Generate documentation
      # - name: Generate docs
      #   run: zenv docs > ENVIRONMENT.md

      # Optional: Check for secrets
      # - name: Detect secrets
      #   run: zenv check --detect-secrets
"#,
        if use_binary { " --use-binary" } else { "" },
        install_step
    )
}

/// GitLab CI template
fn gitlab_ci_template(use_binary: bool) -> String {
    let install_script = if use_binary {
        format!(
            r#"    - curl -fsSL {} -o zenv
    - chmod +x zenv
    - mv zenv /usr/local/bin/"#,
            RELEASE_BINARY_URL
        )
    } else {
        "    - cargo install zorath-env --locked".to_string()
    };

    let image = if use_binary {
        BINARY_IMAGE
    } else {
        RUST_LATEST_IMAGE
    };
    let extra_deps = if use_binary {
        "\n    - apt-get update && apt-get install -y --no-install-recommends ca-certificates curl"
    } else {
        ""
    };

    let docs_example = format!(
        "Optional: Generate documentation as artifact\ngenerate-docs:\n  stage: validate\n  image: {image}\n  before_script:{extra_deps}\n{install_script}\n  script:\n    - zenv docs > ENVIRONMENT.md\n  artifacts:\n    paths:\n      - ENVIRONMENT.md"
    )
    .lines()
    .map(|line| format!("# {line}"))
    .collect::<Vec<_>>()
    .join("\n");

    format!(
        r#"# .gitlab-ci.yml
# Generated by zenv template gitlab{}
stages:
  - validate

validate-env:
  stage: validate
  image: {}
  before_script:{}
{}
  script:
    - zenv check --allow-missing-env
  rules:
    - changes:
        - .env*
        - env.schema.json
        - env.schema.yaml

{}
"#,
        if use_binary { " --use-binary" } else { "" },
        image,
        extra_deps,
        install_script,
        docs_example
    )
}

/// CircleCI config template
fn circleci_template(use_binary: bool) -> String {
    if use_binary {
        format!(
            r#"# .circleci/config.yml
# Generated by zenv template circleci --use-binary
version: 2.1

executors:
  linux:
    docker:
      - image: {}

jobs:
  validate-env:
    executor: linux
    steps:
      - run:
          name: Install dependencies
          command: apt-get update && apt-get install -y --no-install-recommends ca-certificates curl git openssh-client
      - checkout
      - run:
          name: Install zenv
          command: |
            curl -fsSL {} -o zenv
            chmod +x zenv
            mv zenv /usr/local/bin/
      - run:
          name: Validate .env
          command: zenv check --allow-missing-env

workflows:
  version: 2
  validate:
    jobs:
      - validate-env:
          filters:
            branches:
              only:
                - main
                - develop
"#,
            BINARY_IMAGE, RELEASE_BINARY_URL
        )
    } else {
        format!(
            r#"# .circleci/config.yml
# Generated by zenv template circleci
version: 2.1

executors:
  rust:
    docker:
      - image: {}

jobs:
  validate-env:
    executor: rust
    steps:
      - checkout
      - run:
          name: Install zenv
          command: cargo install zorath-env --locked
      - run:
          name: Validate .env
          command: zenv check --allow-missing-env

workflows:
  version: 2
  validate:
    jobs:
      - validate-env:
          filters:
            branches:
              only:
                - main
                - develop
"#,
            RUST_CIRCLE_IMAGE
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn binary_templates_use_the_published_asset_and_compatible_runtime() {
        for template in [
            github_actions_template(true),
            gitlab_ci_template(true),
            circleci_template(true),
        ] {
            assert!(template.contains(RELEASE_BINARY_URL));
            assert!(template.contains("-o zenv"));
            assert!(template.contains("chmod +x zenv"));
            assert!(!template.contains("tar xz") && !template.contains("alpine"));
            let parsed: serde_json::Value = serde_saphyr::from_str(&template).unwrap();
            assert!(parsed.is_object());
        }
        let release = include_str!("../../.github/workflows/release.yml");
        assert!(release.contains("name: zenv-linux"));
        assert!(release.contains("os: ubuntu-24.04"));
        assert!(RELEASE_BINARY_URL.ends_with("/zenv-linux"));
    }

    #[test]
    fn source_templates_use_locked_dependencies_and_supported_rust() {
        for template in [
            github_actions_template(false),
            gitlab_ci_template(false),
            circleci_template(false),
        ] {
            assert!(template.contains("cargo install zorath-env --locked"));
            let parsed: serde_json::Value = serde_saphyr::from_str(&template).unwrap();
            assert!(parsed.is_object());
        }
        assert_eq!(
            RUST_CIRCLE_IMAGE,
            format!("cimg/rust:{}", env!("CARGO_PKG_RUST_VERSION"))
        );
    }

    #[test]
    fn test_github_template_contains_workflow() {
        let template = github_actions_template(false);
        assert!(template.contains("name: Validate Environment"));
        assert!(template.contains("zenv check"));
        assert!(template.contains("cargo install zorath-env"));
    }

    #[test]
    fn test_github_template_binary_mode() {
        let template = github_actions_template(true);
        assert!(template.contains("name: Validate Environment"));
        assert!(template.contains("zenv check"));
        assert!(template.contains("curl -fsSL"));
        assert!(!template.contains("cargo install"));
    }

    #[test]
    fn test_gitlab_template_contains_stages() {
        let template = gitlab_ci_template(false);
        assert!(template.contains("stages:"));
        assert!(template.contains("validate-env:"));
        assert!(template.contains("cargo install zorath-env"));
    }

    #[test]
    fn test_gitlab_template_binary_mode() {
        let template = gitlab_ci_template(true);
        assert!(template.contains("stages:"));
        assert!(template.contains("validate-env:"));
        assert!(template.contains("curl -fsSL"));
        assert!(template.contains(BINARY_IMAGE));
        let parsed: serde_json::Value = serde_saphyr::from_str(&template).unwrap();
        assert_eq!(parsed["validate-env"]["rules"].as_array().unwrap().len(), 1);
    }

    #[test]
    fn test_circleci_template_contains_jobs() {
        let template = circleci_template(false);
        assert!(template.contains("version: 2.1"));
        assert!(template.contains("validate-env:"));
        assert!(template.contains("cargo install zorath-env"));
    }

    #[test]
    fn test_circleci_template_binary_mode() {
        let template = circleci_template(true);
        assert!(template.contains("version: 2.1"));
        assert!(template.contains("validate-env:"));
        assert!(template.contains("curl -fsSL"));
        assert!(template.contains(BINARY_IMAGE));
    }

    #[test]
    fn test_run_list_templates() {
        let result = run("", None, true, false);
        assert!(result.is_ok());
    }

    #[test]
    fn test_run_unknown_template() {
        let result = run("unknown", None, false, false);
        assert!(result.is_err());
        assert!(result.unwrap_err().to_string().contains("Unknown template"));
    }

    #[test]
    fn test_template_aliases() {
        // Test that aliases work
        let gh = run("gh", None, false, false);
        assert!(gh.is_ok());

        let gl = run("gl", None, false, false);
        assert!(gl.is_ok());

        let circle = run("circle", None, false, false);
        assert!(circle.is_ok());
    }
}
